import React, { useEffect, useState } from 'react';
import { captionsSrtUrl, getCaptions, saveCaptions, type CaptionCue, type CaptionSettings } from '../api/client';

interface Props {
  projectId: string;
  onClose: () => void;
  // Called after the settings are saved, so the preview reloads the overlay.
  onSaved: (settings: CaptionSettings) => void;
  onSeek: (seconds: number) => void;
}

const fmtTime = (s: number) => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, '0')}`;

const MODES: { value: CaptionSettings['mode']; label: string; hint: string }[] = [
  { value: 'off', label: 'Off', hint: 'No captions.' },
  { value: 'burn', label: 'Burn into the video', hint: 'Drawn on the preview and every export, and saved as an .srt next to exports.' },
  { value: 'srt', label: 'Subtitle file only', hint: 'Not drawn; exports also save captions.srt to load in a player or upload with the video.' },
];

// Captions are made from the voiceover lines or the transcript; nothing here is generated by AI, so
// changes are instant and free.
export const CaptionsDialog: React.FC<Props> = ({ projectId, onClose, onSaved, onSeek }) => {
  const [settings, setSettings] = useState<CaptionSettings | null>(null);
  const [cues, setCues] = useState<CaptionCue[]>([]);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    getCaptions(projectId)
      .then((r) => {
        setSettings(r.settings);
        setCues(r.cues);
      })
      .catch((e) => setError(e instanceof Error ? e.message : String(e)));
  }, [projectId]);

  const update = async (patch: Partial<CaptionSettings>) => {
    if (!settings) return;
    const next = { ...settings, ...patch };
    setSettings(next);
    setSaving(true);
    setError(null);
    try {
      const saved = await saveCaptions(projectId, next);
      setCues(saved.cues);
      onSaved(saved.settings);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="modal-backdrop" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className="modal" role="dialog" aria-label="Captions">
        <div className="modal-header">
          <h3 className="inspector-heading" style={{ margin: 0 }}>
            Captions
          </h3>
          <div style={{ flex: 1 }} />
          {saving && <span style={{ fontSize: 12, color: 'var(--text-faint)' }}>Saving…</span>}
          <button type="button" className="btn btn-ghost btn-sm" onClick={onClose}>
            Close
          </button>
        </div>
        <div className="panel-hint">
          Captions are made from your voiceover lines or the video's transcript, so they are free and update by themselves when
          the text changes.
        </div>
        {error && <div className="field-error">{error}</div>}
        {settings && (
          <>
            <div style={{ display: 'flex', flexDirection: 'column', gap: 6, margin: '12px 0' }}>
              {MODES.map((m) => (
                <label key={m.value} style={{ display: 'flex', gap: 8, alignItems: 'flex-start', fontSize: 13 }}>
                  <input type="radio" name="caption-mode" checked={settings.mode === m.value} onChange={() => update({ mode: m.value })} />
                  <span>
                    {m.label}
                    <span style={{ display: 'block', fontSize: 11.5, color: 'var(--text-faint)' }}>{m.hint}</span>
                  </span>
                </label>
              ))}
            </div>
            <div style={{ display: 'flex', gap: 12, flexWrap: 'wrap', marginBottom: 12 }}>
              <label className="capture-label" style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
                Text from
                <select
                  className="field-select"
                  style={{ width: 'auto', padding: '5px 8px' }}
                  value={settings.source}
                  onChange={(e) => update({ source: e.target.value as CaptionSettings['source'] })}
                >
                  <option value="auto">Voiceover, or transcript if none</option>
                  <option value="voiceover">Voiceover</option>
                  <option value="transcript">Transcript</option>
                </select>
              </label>
              <label className="capture-label" style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
                Position
                <select
                  className="field-select"
                  style={{ width: 'auto', padding: '5px 8px' }}
                  value={settings.position}
                  onChange={(e) => update({ position: e.target.value as CaptionSettings['position'] })}
                  disabled={settings.mode !== 'burn'}
                >
                  <option value="bottom">Bottom</option>
                  <option value="top">Top</option>
                </select>
              </label>
              <label className="capture-label" style={{ display: 'flex', alignItems: 'center', gap: 6 }}>
                Size
                <select
                  className="field-select"
                  style={{ width: 'auto', padding: '5px 8px' }}
                  value={settings.size}
                  onChange={(e) => update({ size: e.target.value as CaptionSettings['size'] })}
                  disabled={settings.mode !== 'burn'}
                >
                  <option value="small">Small</option>
                  <option value="medium">Medium</option>
                  <option value="large">Large</option>
                </select>
              </label>
              {cues.length > 0 && (
                <a className="btn btn-sm" href={captionsSrtUrl(projectId)} download>
                  Download .srt
                </a>
              )}
            </div>
            {cues.length === 0 ? (
              <div className="inspector-empty">
                No caption text yet. Add voiceover lines to markers, or transcribe the video.
              </div>
            ) : (
              <div style={{ display: 'flex', flexDirection: 'column', gap: 4, maxHeight: 320, overflowY: 'auto' }}>
                {cues.map((c, i) => (
                  <div key={i} style={{ display: 'flex', gap: 10, alignItems: 'baseline', fontSize: 13 }}>
                    <button
                      type="button"
                      className="btn btn-ghost btn-sm"
                      style={{ flex: 'none', fontFamily: 'var(--font-mono)', fontSize: 11.5 }}
                      onClick={() => onSeek(c.start)}
                      title="Jump the preview to this caption"
                    >
                      {fmtTime(c.start)}
                    </button>
                    <span>{c.text}</span>
                  </div>
                ))}
              </div>
            )}
          </>
        )}
      </div>
    </div>
  );
};
