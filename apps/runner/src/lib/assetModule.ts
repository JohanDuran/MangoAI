import fs from 'node:fs';
import path from 'node:path';
import { projectDir } from './paths.js';
import { readCompositionConfig, updateCompositionConfig } from './composition.js';
import { runnerUrl } from './skills.js';

const assetsModule = (projectId: string) => `// GENERATED BY THE RUNNER — do not edit.
import config from './CompositionConfig.json';

// URL of an image in the project's library, e.g. assetUrl('up_1a2b3c4d.jpg'). It resolves against the
// runner that currently serves this project, so it keeps working if the runner's port changes.
export const assetUrl = (file: string): string => \`\${config.runnerUrl}/projects/${projectId}/assets/\${file}\`;
`;

// Keeps 03_remotion_code/assets.ts (the assetUrl helper markers import) and the runner address in
// CompositionConfig.json current. Writes only when something changed, so calling it often does not
// trigger reloads in the editor.
export function syncAssetModule(id: string): void {
  const dir = path.join(projectDir(id), '03_remotion_code');
  if (!fs.existsSync(dir)) return;
  if (readCompositionConfig(id).runnerUrl !== runnerUrl()) updateCompositionConfig(id, { runnerUrl: runnerUrl() });
  const target = path.join(dir, 'assets.ts');
  const content = assetsModule(id);
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf-8') !== content) fs.writeFileSync(target, content);
}
